#include <string>

class BasicShape {
private:
	double area;
	string name;
public:
	BasicShape(string n, double area) : name(n), area(a) {}

	double getArea() {
		return area;
	}
	string getName() {
		return name;
	}

	void setArea(double a) {
		area = a;
	}
	void setName(string n) {
		name = n;
	}

};



